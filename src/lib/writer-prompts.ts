export function styleAnalysisInstruction() {
  return `完整阅读这一篇原稿，写一份具体、深入的单篇风格分析，供后续与其他作品一起归纳作者风格。
重点理解这个作者怎样从素材里发现角度，怎样揣摩观众已有的认识和情绪，怎样安排信息让人继续听，以及具体话术、句式、原声、铺垫、转折、类比、调侃和收尾如何配合。沿着原稿实际展开，说明观众的理解或情绪怎样被一步步建立、改变和接住。
不要用“口语化、有网感、节奏快、有反差”等标签代替分析，也不要只统计口头禅。作者确有长铺垫、绕话、重复、改口或激烈表达时，分析它在这里怎样起作用，不先替作者润色。
只看表达方式，不把本篇的事实、人物或题材当成新稿要求。按真正有辨识度的发现自然组织，不必逐项作答；不拆成用途、场景边界、段落节拍、衔接规则或限制清单，也不补免责声明、证据审计和通用写作建议。
summary 可以写成多段，篇幅由原稿的特点决定。可以另选 0—3 句最有代表性的连续原句，不需要逐段举证。只输出 JSON：
{"summary":"具体、深入的单篇表达分析","quotes":["连续原句"]}
原句必须来自原文，保持原字，不拼接；没有合适的就返回空数组。`;
}

export function styleCardInstruction() {
  return `根据这些逐篇分析，写一份具体、深入的作者风格学习笔记，让另一个写手学会他的思考和表达。
重点拆解：作者怎样从素材里发现角度，怎样揣摩观众已有的认识和情绪，怎样安排信息让人继续听，以及具体话术、句式、原声、铺垫、转折和收尾如何配合。
结合逐篇分析和其中前后相接的原话，说明这些话分别做了什么、观众的理解怎么变化、换个题材时能借鉴什么思路。对照不同作品，讲出稳定习惯和有意义的变化，避免用“口语化、有反差、节奏快”等标签代替分析。
少量保留最有代表性的连续原句即可，格式为 [[来源ID]]「原句」，不要求每个发现都举证。只能逐字复制每篇“可引用原句”中明确列出的内容，分析正文里提到但未单列的句子不能引用；原句与自己拟的示例明确区分。
按发现自然组织，在 3000—4500 个汉字左右写完整，不为覆盖每篇而重复同类结论。全文聚焦这个作者的创作方法，不另加通用写作教程、固定模板、检查清单、免责声明、证据审计或边界提醒，也不把旧事件当成新稿要求。只输出自然连贯的 Markdown 风格卡正文。`;
}

